def region_of(uezd):
    return UEZDS[uezd][0]


def census_rank(key):
    return list(CENSUS).index(key)


def place_label(p):
    """«Лавельская волость», «Кевроль (город)», «Боровская, деревня»."""
    k = p["kind"]
    if "погост" in p["name"] or "гора" in p["name"]:
        return f"{p['name']} ({k})"
    if k in ("волость", "слобода", "стан", "уезд", "острог", "сельское общество"):
        return f"{p['name']} {k}"
    return f"{p['name']}, {k}"


def validate(c):
    """Список ошибок в новых полях записи; пустой — всё в словарях."""
    err = []
    for u in c.get("uezd") or []:
        if u not in UEZDS:
            err.append(f"уезд «{u}» не в geo.UEZDS")
    if not c.get("uezd"):
        err.append("нет уезда")
    if c.get("kind") not in KINDS:
        err.append(f"вид «{c.get('kind')}» не в geo.KINDS")
    if c.get("census") is not None and c["census"] not in CENSUS:
        err.append(f"волна «{c['census']}» не в geo.CENSUS")
    for e in c.get("estates") or []:
        if e not in ESTATES:
            err.append(f"сословие «{e}» не в geo.ESTATES")
    multi = len(c.get("uezd") or []) > 1
    for p in c.get("places") or []:
        if p.get("kind") not in PLACE_KINDS:
            err.append(f"место {p.get('name')}: вид «{p.get('kind')}» не в geo.PLACE_KINDS")
        if p.get("kind") == "уезд" and p["name"] not in (c.get("uezd") or []):
            err.append(f"часть «{p['name']}» не входит в уезды дела")
        if multi and p.get("kind") != "уезд" and p.get("uezd") not in (c.get("uezd") or []):
            err.append(f"место {p['name']}: у дела несколько уездов, нужен свой `uezd`")
    for y in ("year_from", "year_to"):
        if c.get(y) is not None and not isinstance(c[y], int):
            err.append(f"{y} должен быть числом")
    return err
